// A placed piece copied: its model, turn, scale and light, and whether it holds - never what it holds, its craft, or
// that it is the player's own. Leaving the placement writes nothing and charges nothing.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { toolRig, placeFrom, all, rows, settle } from '../../decorFakes.mjs';

const panel = (rig) => rig.doc.body.children.find((c) => c.className === 'dfdecor');
const press = (root, re) => all(root, 'dfdecor-btn').find((b) => re.test(b.textContent));
const roomOf = (root) => all(root, 'dfdecor-chip').find((c) => /^In this room/.test(c.textContent));

test('a duplicate copies the look and not the contents, and a cancelled copy is never placed or paid', async () => {
  const rig = toolRig({ gold: 5000 });
  await placeFrom(rig, 'm41000');
  assert.equal(await rig.tool.commit(), true);
  rig.tool.back();
  const first = rig.standing[0];
  first.rot = [30, 0, 0];
  first.scale = 1.5;
  first.light = { color: [1, 0.8, 0.4], range: 5, intensity: 0.6 };
  first.storage = true;
  first.station = 'alchemy';
  rig.holds.add(first.id);
  const gold = rig.w.gold;
  rig.frame({ overlayUp: true });
  const root = panel(rig);
  roomOf(root).fire('click');
  rows(root).find((r) => r.dataset.key === first.id).fire('click');
  first.item = { id: 'pack-1' };
  rig.frame({ overlayUp: true });
  assert.equal(press(root, /^Duplicate$/).disabled, true, 'one\'s own is taken down, not copied');
  press(root, /^Duplicate$/).fire('click');
  assert.equal(rig.tool.ghost(), null);
  delete first.item;
  rig.frame({ overlayUp: true });
  press(root, /^Duplicate$/).fire('click');
  rig.frame();
  await settle();
  rig.frame();
  const g = rig.tool.ghost();
  assert.ok(g && g.id !== first.id);
  assert.equal(g.rot[0], 30);
  assert.equal(g.scale, 1.5);
  assert.deepEqual([...g.light.color], [1, 0.8, 0.4]);
  assert.equal(g.light.range, 5);
  assert.equal(g.storage, true);
  assert.equal(g.station, undefined);
  assert.equal(g.item ?? null, null);
  assert.equal(rig.holds.has(g.id), false);
  assert.equal(rig.standing.length, 1);
  assert.equal(rig.w.gold, gold);
  rig.tool.back();
  assert.equal(rig.standing.length, 1);
  assert.equal(rig.w.gold, gold, 'leaving the copy charges nothing');
  assert.equal(rig.tool.flying(), true);
  assert.equal(rig.tool.panelOpen(), false);
  assert.equal(rig.tool.openPanel(), true);
  const again = panel(rig);
  roomOf(again).fire('click');
  rows(again).find((r) => r.dataset.key === first.id).fire('click');
  press(again, /^Duplicate$/).fire('click');
  rig.frame();
  await settle();
  rig.frame();
  assert.equal(await rig.tool.commit(), true);
  assert.equal(rig.standing.length, 2);
  const copy = rig.standing.find((p) => p.id !== first.id);
  assert.equal(copy.model, first.model);
  assert.equal(copy.rot[0], 30);
  assert.equal(copy.scale, 1.5);
  assert.equal(copy.storage, true);
  assert.equal(copy.station, undefined);
  assert.equal(rig.holds.has(copy.id), false);
  assert.equal(rig.holds.has(first.id), true);
  assert.ok(rig.w.gold < gold);
});
