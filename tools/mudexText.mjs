#!/usr/bin/env node
// MUDEX1 (2026-10-20): writes src/systems/enemyExpansion/mudexTableText.js - MUDEX's two tables as TEXT, each the bytes
// of the vendored file of the same name under vendor/mudex/ exactly, in the manifest's order (BestiaryMod.GetDBAssets
// walks an enabled mod's Files). `--check` fails when the module and the vendored files part.
//
//   node tools/mudexText.mjs            write the module
//   node tools/mudexText.mjs --check    exit 1 if the module is not what the files make
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from './lib/isMain.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const VENDOR = join(ROOT, 'vendor/mudex');
export const MUDEX_TEXT_MODULE = 'src/systems/enemyExpansion/mudexTableText.js';

/** The module's source: the manifest's files, in its order, as their bytes. */
export function mudexTextSource() {
  const manifest = JSON.parse(readFileSync(join(VENDOR, 'MUDEX.dfmod.json'), 'utf8'));
  const entries = manifest.Files.map((f) => basename(f)).map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(readFileSync(join(VENDOR, name), 'utf8'))},`);
  return [
    '// GENERATED by tools/mudexText.mjs from vendor/mudex (MUDEX 1.0.1, Ralzar) - do not edit.',
    '// The mod\'s two tables as TEXT, each the bytes of the vendored file of the same name exactly, in the manifest\'s order',
    '// (BestiaryMod.GetDBAssets walks its Files): what systems/enemyExpansion/dexTables.js reads after DEX\'s own, with DEX\'s',
    '// CSV helpers, when MUDEX is loaded beside it (systems/enemyExpansion/dexSwitches.js).',
    'export const MUDEX_TABLE_TEXT = Object.freeze({',
    ...entries,
    '});',
    '',
  ].join('\n');
}

if (isMain(import.meta.url)) {
  const path = join(ROOT, MUDEX_TEXT_MODULE);
  const want = mudexTextSource();
  if (process.argv.includes('--check')) {
    const have = readFileSync(path, 'utf8');
    if (have !== want) { console.error(`${MUDEX_TEXT_MODULE} is not what vendor/mudex makes - run node tools/mudexText.mjs`); process.exit(1); }
    console.log(`${MUDEX_TEXT_MODULE}: current`);
  } else {
    writeFileSync(path, want);
    console.log(`wrote ${MUDEX_TEXT_MODULE}`);
  }
}
