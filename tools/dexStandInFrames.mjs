#!/usr/bin/env node
// ARN3 (2026-10-26) - THE CLASSIC ARCHIVES THE ENEMY EXPANSION'S STAND-INS COPY, COUNTED. A copy registers each of its
// records' frames before the player's TEXTURE file is read (systems/enemyExpansion/dexStandIns.js), so how many each
// record has is written down here, off the player's own ARENA2: numbers about the files, never a pixel of them.
//
//   node tools/dexStandInFrames.mjs [<arena2>]           write src/systems/enemyExpansion/dexClassicFrames.js
//   node tools/dexStandInFrames.mjs [<arena2>] --check   exit 1 if the file on disk is not what the data says
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TextureFile, texName } from '../src/formats/textureFile.js';
import { DEX_STAND_INS } from '../src/systems/enemyExpansion/dexStandIns.js';
import { isMain } from './lib/isMain.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'src/systems/enemyExpansion/dexClassicFrames.js';

/** Every classic archive a stand-in copies, by its records' frame counts. */
export function countClassicFrames(arena2) {
  const out = {};
  for (const a of [...new Set(Object.values(DEX_STAND_INS).map((s) => s.classic).filter(Boolean))].sort((x, y) => x - y)) {
    const t = new TextureFile();
    if (!t.load(new Uint8Array(readFileSync(join(arena2, texName(a)))), texName(a))) throw new Error(`${texName(a)} would not read`);
    out[a] = Array.from({ length: t.recordCount }, (_, r) => t.getFrameCount(r));
  }
  return out;
}

export function classicFramesText(counts) {
  const rows = Object.entries(counts).map(([a, f]) => `  ${a}: [${f.join(',')}],`).join('\n');
  return `// GENERATED by tools/dexStandInFrames.mjs from the player's own ARENA2 - do not edit. Each classic archive the Enemy
// Expansion's stand-ins copy (dexStandIns.js), by its records' frame counts: numbers about the files, never their pixels.
export const DEX_CLASSIC_FRAMES = Object.freeze({
${rows}
});
`;
}

if (isMain(import.meta.url)) {
  const arena2 = process.argv.slice(2).find((a) => !a.startsWith('--')) ?? process.env.ARENA2_PATH ?? '/home/claude/dfdata/arena2';
  const text = classicFramesText(countClassicFrames(arena2));
  if (process.argv.includes('--check')) {
    const same = readFileSync(join(ROOT, OUT), 'utf8') === text;
    console.log(same ? `${OUT} is the data's` : `${OUT} differs from the data - run without --check`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(join(ROOT, OUT), text);
  console.log(`wrote ${OUT}`);
}
