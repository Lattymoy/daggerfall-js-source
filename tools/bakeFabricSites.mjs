// QUEST-FABRIC (2026-10-26, the owner, asked whether quests may land in BLD-3's buildings: "Let quests use them";
// bible/06-Systems/Quest-Arc.md QUEST-FABRIC) - THE IMPERIAL CITY'S FABRIC AS A SITES INDEX READS IT, BAKED.
//
//     ARENA2_PATH=... node tools/bakeFabricSites.mjs           write src/world/imperialFabricSites.js
//     ARENA2_PATH=... node tools/bakeFabricSites.mjs --check   say whether it is the plan's and BLOCKS.BSA's
//
// A capital slice's sites index (systems/quest/place.js townSitesIndex, kept a slice by scenes/quest/questProvinceSites.js)
// is the kinds of building a search could take there. Its fabric half is the kinds of the slice's own cells' buildings
// whose donor's interior holds a quest marker (world/imperialFabricBuildings.js fabricSliceKindsOf) - and laid out cell by
// cell that is some 0.1 s a slice: a temple's darts over the city read some ninety slices' indexes, 12 s of a 15 s parse.
// It is a law of the plan (world/imperialFabric.js, world/imperialFabricBuildings.js) and of the donors' interiors
// (BLOCKS.BSA, the freeware's), so it is baked: which donors are marked, and for each of the plan's slices its set of kinds,
// each distinct set once. test/systems/quest/questfabric.test.js holds the table to the plan on a spread of slices, and to
// BLOCKS.BSA where it is at hand; this tool's --check reads every slice (some 30 s).
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BlocksFile } from '../src/formats/blocksFile.js';
import { FABRIC_DONORS, fabricSliceKindsOf } from '../src/world/imperialFabricBuildings.js';
import { buildingHasQuestMarker } from '../src/systems/quest/place.js';
import { IMPERIAL_SPAN } from '../src/world/imperialCity.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'src/world/imperialFabricSites.js');
const A = process.env.ARENA2_PATH;
if (!A) {
  console.error('ARENA2_PATH names no freeware (sh tools/fetch-data.sh)');
  process.exit(2);
}
const raw = readFileSync(join(A, 'BLOCKS.BSA'));
const blocks = new BlocksFile();
blocks.load(new Uint8Array(raw.buffer, raw.byteOffset, raw.byteLength));
const marked = FABRIC_DONORS.map((d) => buildingHasQuestMarker(blocks.getBlockByName(d.block), d.record));
const sets = [''],
  ids = new Map([['', 0]]),
  slices = [];
for (let s = 0; s < IMPERIAL_SPAN * IMPERIAL_SPAN; s++) {
  const k = fabricSliceKindsOf(s, marked).join(' ');
  if (!ids.has(k)) {
    ids.set(k, sets.length);
    sets.push(k);
  }
  slices.push(ids.get(k));
}
const text = `// GENERATED by tools/bakeFabricSites.mjs (QUEST-FABRIC, bible/06-Systems/Quest-Arc.md) - do not edit by hand: run it with
// ARENA2_PATH set, and \`--check\` to hold it. The Imperial City's fabric as a capital slice's sites index reads it
// (world/imperialFabricBuildings.js fabricSliceKindsOf, fabricSliceSites).

/** Which of FABRIC_DONORS' interiors hold a quest marker (BLOCKS.BSA's), by FABRIC_DONORS' order, 1 or 0. */
export const FABRIC_DONOR_MARKED = Object.freeze([${marked.map(Number).join(', ')}]);
/** Each distinct set of \`type:faction\` a slice's fabric gives, the first none. */
export const FABRIC_SITE_SETS = Object.freeze([
${sets.map((x) => `  '${x}',`).join('\n')}
]);
/** Slice s's set (s = its row * ${IMPERIAL_SPAN} + its column), an index into FABRIC_SITE_SETS. */
export const FABRIC_SLICE_SETS = Object.freeze([
${Array.from({ length: IMPERIAL_SPAN }, (_, r) => `  ${slices.slice(r * IMPERIAL_SPAN, (r + 1) * IMPERIAL_SPAN).join(', ')},`).join('\n')}
]);
`;
if (process.argv.includes('--check')) {
  const was = readFileSync(OUT, 'utf8');
  if (was !== text) {
    console.error(
      "src/world/imperialFabricSites.js is not the plan's and BLOCKS.BSA's: run node tools/bakeFabricSites.mjs",
    );
    process.exit(1);
  }
  console.log(
    `src/world/imperialFabricSites.js: ${slices.length} slices, ${sets.length} sets, ${marked.filter(Boolean).length} of ${marked.length} donors marked - in step`,
  );
} else {
  writeFileSync(OUT, text);
  console.log(
    `wrote src/world/imperialFabricSites.js: ${slices.length} slices, ${sets.length} sets, ${marked.filter(Boolean).length} of ${marked.length} donors marked`,
  );
}
