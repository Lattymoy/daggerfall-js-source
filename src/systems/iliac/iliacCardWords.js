/** The ids the words are written for - every card and every holding of the set (pinned equal to the catalog's). */
export const CARD_WORD_IDS = Object.freeze(Object.keys(WORDS));
const wordsOf = (/** @type {any} */ card) => (typeof card?.id === 'string' && Object.hasOwn(WORDS, card.id) ? WORDS[card.id] : null);
/** A card's rules in the player's language - '' for a card the set does not hold. @param {any} card */
export const cardRules = (card) => wordsOf(card)?.[0]() ?? '';
/** A card's flavor in the player's language - '' for a card the set does not hold. @param {any} card */
export const cardFlavor = (card) => wordsOf(card)?.[1]() ?? '';
/** Both, as a painter takes them. @param {any} card @returns {{rules: string, flavor: string}} */
export const cardWords = (card) => ({ rules: cardRules(card), flavor: cardFlavor(card) });
