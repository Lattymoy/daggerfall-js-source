/** Whether map pixel (x, y) is Bantha's. Pure. */
export function banthaAreaHas(x, y) {
  const r = _byRow[y - ROW0];
  if (!r) return false;
  for (let k = 1; k < r.length; k += 2) if (x >= r[k] && x <= r[k + 1]) return true;
  return false;
}
