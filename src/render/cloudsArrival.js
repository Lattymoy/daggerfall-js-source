// @ts-check
// CLOUD-COMPILE (2026-10-26; bible/07-Rendering/Performance-Priority.md CLOUD-COMPILE): THE VOLUMETRIC CLOUDS ARRIVE
// WHEN THEIR PROGRAMS ARE DONE.
//
// The clouds' march program is the boot's longest single compile on D3D11 (seconds, against a fraction of a second on
// Vulkan). BOOT-COMPILE starts it as soon as the renderer exists, but on a busy machine it was still compiling when the
// sky controller built the clouds, and that build waited for it on the page's thread. Nothing the game is played by
// reads the clouds, so the sky does not wait for them: it draws as it does with the clouds off (the dome's own decks,
// the dome's own shadow on the ground) until the driver says the clouds' programs are done. Then the clouds are built,
// and they take over the sky once their first sweep of the sky map is marched, so no frame shows a sky with neither.
import { compiledPass, parallelCompile, startPrograms } from './glProgram.js';
import { VolumetricClouds, CLOUD_PROGRAMS } from './volumetricClouds.js';
import { CLOUD_NOISE_PROGRAMS } from './cloudNoise.js';

/** Every program the clouds' constructor builds: the noise's three and the clouds' own four. */
export const CLOUDS_ARRIVAL_PROGRAMS = Object.freeze([...CLOUD_NOISE_PROGRAMS, ...CLOUD_PROGRAMS]);

/**
 * @typedef {object} CloudsArrival
 * @property {(viewport: number[]) => VolumetricClouds|null} poll  The clouds, built the first time this is asked after
 *   the driver has finished their programs - null until then, and null for good if the build failed. The build draws
 *   (the noise is generated by drawing) and restores `viewport`, so call it where the clouds' own march runs: inside
 *   the sky's draw, which the hosts already mark as a foreign pass.
 * @property {() => VolumetricClouds|null} shown  The clouds once their first sweep of the sky map is marched - what
 *   the sky draws and the ground's shadow reads. Null before: the sky stands as it does with the clouds off.
 * @property {(offset: ArrayLike<number>) => void} offsetOrigin  The host's floating-origin recenter. Before the clouds
 *   are built the offsets are summed and handed to them at their build, so their field is sampled where it would have
 *   been had they been built at the boot.
 */

/** The clouds' door for the sky controller.
 *  @param {WebGL2RenderingContext} gl @param {string} quality a volumetricClouds.js QUALITY key
 *  @param {string|null} testCellSpec the `?cloudcell=` door's text, handed to the clouds at their build
 *  @returns {CloudsArrival} */
export function createCloudsArrival(gl, quality, testCellSpec) {
  const pendingOffset = [0, 0, 0];
  let offsetPending = false;
  let clouds = /** @type {VolumetricClouds|null} */ (null);
  let buildViewport = /** @type {number[]} */ ([0, 0, gl.drawingBufferWidth, gl.drawingBufferHeight]);
  let shownOnce = false;

  const build = () => {
    const built = new VolumetricClouds(gl, quality, buildViewport);
    built.testCellSpec = testCellSpec;
    if (offsetPending) built.offsetOrigin(pendingOffset);
    // A probe reads when the clouds arrive on the page's own clock (tools: the boot's first world frame beside it).
    globalThis.performance?.mark?.('clouds-built');
    return built;
  };
  // The clouds are never needed this frame (nothing played reads them), so the door is never forced: get() with no
  // argument waits for the driver however long it takes. Until then each ask polls the seven programs' completion,
  // which waits on nothing (SHADER-STALL measured 0-0.4 ms a poll).
  const door = compiledPass(gl, CLOUDS_ARRIVAL_PROGRAMS, build, (e) => console.warn('[clouds] the volumetric clouds could not be built - the sky stands without them', e));
  // Started at the controller's mount, not at the sky's first draw: the boot started them already (bootPrograms.js), and
  // a sky whose switches the boot read otherwise compiles from here. Where the driver cannot compile beside the page,
  // nothing is started - a link queued ahead would hold the page's next GL read.
  if (parallelCompile(gl)) startPrograms(gl, CLOUDS_ARRIVAL_PROGRAMS);

  return {
    poll(viewport) {
      buildViewport = viewport;
      clouds ??= door();
      return clouds;
    },
    shown() {
      if (!clouds || clouds.sweeps === 0) return null;
      if (!shownOnce) {
        shownOnce = true;
        globalThis.performance?.mark?.('clouds-shown');
      }
      return clouds;
    },
    offsetOrigin(offset) {
      if (clouds) {
        clouds.offsetOrigin(offset);
        return;
      }
      pendingOffset[0] += offset[0];
      pendingOffset[2] += offset[2];
      offsetPending = true;
    },
  };
}
