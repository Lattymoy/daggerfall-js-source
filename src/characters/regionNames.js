/** The text's own hash (FNV-1a). @param {string} s */
export function nameHash(s) {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return h >>> 0;
}
/** Two numbers mixed into one seed. @param {number} a @param {number} b */
export const mixSeed = (a, b) => {
  let h = Math.imul((a >>> 0) ^ 0x9e3779b9, 0x85ebca6b) ^ Math.imul((b >>> 0) + 0x6a09e667, 0xc2b2ae35);
  h ^= h >>> 15;
  h = Math.imul(h, 0x2c1b3c6d);
  h ^= h >>> 12;
  return h >>> 0;
};
/** A small seeded stream (mulberry32) in [0, 1). @param {number} seed */
function stream(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** One of `list`, a region's fashion favouring a third of it three to one (`fashion` a seed, 0 for none).
 *  @template T @param {() => number} r @param {readonly T[]} list @param {number} [fashion] @returns {T} */
function pick(r, list, fashion = 0) {
  if (!fashion || list.length < 4) return list[Math.floor(r() * list.length)];
  const cum = fashionOf(list, fashion);
  const x = r() * cum[cum.length - 1];
  let i = 0;
  while (i < cum.length - 1 && x >= cum[i]) i++;
  return list[i];
}
/** @type {WeakMap<readonly any[], Map<number, Float64Array>>} */
const _fashions = new WeakMap();
/** A list's running weights under a fashion, kept: a census names hundreds on one region's fashions.
 *  @param {readonly any[]} list @param {number} fashion */
function fashionOf(list, fashion) {
  let byFashion = _fashions.get(list);
  if (!byFashion) _fashions.set(list, (byFashion = new Map()));
  let cum = byFashion.get(fashion);
  if (!cum) {
    cum = new Float64Array(list.length);
    for (let i = 0, t = 0; i < list.length; i++) cum[i] = t += mixSeed(fashion, i) % 3 === 0 ? 3 : 1;
    if (byFashion.size > 512) byFashion.clear();
    byFashion.set(fashion, cum);
  }
  return cum;
}
/** A part made of a start and an end: a letter met at the seam before a consonant, or a vowel met there, once (Hild +
 *  dra, never Hilddra; Ili + ias, never Iliias), and none three times. */
function join(a, b) {
  const same = a && b && a[a.length - 1].toLowerCase() === b[0].toLowerCase();
  const seam = same && (/[aeiouy]/i.test(b[0]) || /[^aeiouy]/i.test(b[1] ?? 'a'));
  return (seam ? a + b.slice(1) : a + b).replace(/(.)\1\1+/g, '$1$1');
}
const cap = (s) => (s ? s[0].toUpperCase() + s.slice(1) : s);

