/** LW-PERF: each culture's own hash, and its regions' families and tastes, kept (a census names hundreds at once). */
const HASH = new Map();
const hashOf = (/** @type {string} */ c) => {
  let h = HASH.get(c);
  if (h === undefined) HASH.set(c, (h = nameHash(c)));
  return h;
};
/** @type {Map<string, Map<number, readonly string[]>>} */
const _families = new Map();
/** @type {Map<string, Map<number, Float64Array>>} */
const _tastes = new Map();
/** A region's own keep, kept by culture then region (none past 4096 of a culture). @template T
 *  @param {Map<string, Map<number, T>>} book @param {string} culture @param {number} region @param {() => T} make */
function keptOf(book, culture, region, make) {
  let byRegion = book.get(culture);
  if (!byRegion) book.set(culture, (byRegion = new Map()));
  let out = byRegion.get(region);
  if (out === undefined) {
    if (byRegion.size > 4096) byRegion.clear();
    byRegion.set(region, (out = make()));
  }
  return out;
}
/** The families a region of a culture keeps (REGION_FAMILIES of them), the same for every reader.
 *  @param {Culture} culture @param {number} region @returns {readonly string[]} */
export function regionFamilies(culture, region) {
  return keptOf(_families, culture, region, () => {
    const r = stream(mixSeed(hashOf(culture), region + 0x46));
    const set = new Set();
    for (let i = 0; i < REGION_FAMILIES * 4 && set.size < REGION_FAMILIES; i++)
      set.add(CULTURES[culture].family(r, false));
    return freeze([...set]);
  });
}
/** The families a region keeps, and the share of its people of one of them. */
export const REGION_FAMILIES = 24;
export const REGION_FAMILY_SHARE = 0.45;

/** A region's own weight for each custom, normalized: the culture's share for the place, times the region's own taste
 *  (0.5 to 1.5 each). @param {Culture} culture @param {number} region @param {Ctx} c @returns {number[]} */
export function customWeights(culture, region, c) {
  const customs = CULTURES[culture].customs;
  const taste = keptOf(_tastes, culture, region, () =>
    Float64Array.from(customs, (_, i) => 0.5 + (mixSeed(hashOf(culture) ^ i, region + 0x77) % 1000) / 1000),
  );
  const w = customs.map((k, i) => {
    if (k.key === 'daggerfall' || k.key === 'imperial') {
      if (!c.classic) return 0;
    }
    return k.w(c) * taste[i];
  });
  const total = w.reduce((a, b) => a + b, 0) || 1;
  return w.map((x) => x / total);
}

/**
 * A person's name: their culture's customs as their region keeps them. `seed` the person's own (two people of one
 * seed are one person); `classic` Daggerfall's own name for them, one custom of the Bay's peoples (none: never chosen);
 * `region` a region or an area number (-1 none: the culture's customs alone, no family of a region's); `home` the
 * province or zone they live in (provinceFolk.js keys, null on the Bay; a zone keeps its province's customs).
 * @param {{ culture: Culture, gender: number, seed: number, region?: number, home?: string|null, classic?: string }} o
 * @returns {string}
 */
export function regionName({ culture, gender, seed, region = -1, home = null, classic = '' }) {
  const own = cultureAt(culture, home, seed);
  const def = CULTURES[own] ?? CULTURES.breton;
  const r = stream(mixSeed(seed, hashOf(own)));
  const regional = region >= 0;
  const fams = regional ? regionFamilies(own, region) : null;
  /** @type {Ctx} */
  const c = {
    r,
    female: gender !== MALE,
    classic,
    home: provinceOfHome(home),
    zone: home,
    onBay: regional ? region < BAY_REGIONS : home == null,
    fashion: regional ? mixSeed(hashOf(own), region + 0xfa) : 0,
    fam: () =>
      fams && r() < REGION_FAMILY_SHARE ? fams[Math.floor(r() * fams.length)] : def.family(r, gender !== MALE),
  };
  const w = customWeights(own, regional ? region : 0x7fff, c);
  let x = r(),
    i = 0;
  while (i < w.length - 1 && x >= w[i]) {
    x -= w[i];
    i++;
  }
  const name = def.customs[i].make(c).trim();
  return name || classic || def.customs[def.customs.length - 1].make(c).trim();
}
