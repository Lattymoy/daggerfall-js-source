function redguardGiven(c) {
  const r = c.r;
  let s = pick(r, REDGUARD.onset, c.fashion);
  if (r() < 0.45) s += pick(r, REDGUARD.mid);
  const afterVowel = /[aeiou]$/i.test(s);
  s = join(
    s,
    pick(
      r,
      afterVowel ? (c.female ? REDGUARD.vowelEndF : REDGUARD.vowelEndM) : c.female ? REDGUARD.endF : REDGUARD.endM,
    ),
  );
  if (s.length < 4) s = join(s, pick(r, REDGUARD.mid)); // never a bare syllable (an A and a ha)
  if (r() < 0.12 && s.length > 3) s = `${s.slice(0, 1)}'${s.slice(1).toLowerCase()}`; // Daggerfall's own T'esta
  return cap(s);
}
const nordGiven = (c) => twoPart(c, c.female ? NORD.preF : NORD.preM, c.female ? NORD.sufF : NORD.sufM);
function khajiitRoot(c) {
  let s = pick(c.r, KHAJIIT.roots, c.fashion);
  const twice = c.r() < 0.5;
  if (twice || s.length < 3) s += pick(c.r, KHAJIIT.roots); // never a bare Sa
  return join(s, pick(c.r, c.female ? KHAJIIT.endF : KHAJIIT.endM));
}

