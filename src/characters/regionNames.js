// The customs: a name's whole shape, each culture's in its share (`w`). `home` the province or zone the person lives
// in (characters/provinceFolk.js keys), `onBay` the Iliac Bay's own regions, `fam` a family of the region's.

/** @typedef {{ r: () => number, female: boolean, fashion: number, fam: () => string, classic: string, onBay: boolean,
 *   home: string|null, zone: string|null }} Ctx */
/** @typedef {{ key: string, w: (c: Ctx) => number, make: (c: Ctx) => string }} Custom */

const given = (c, m, f) => pick(c.r, c.female ? f : m, c.fashion);
/** Two consonant sounds at a part's end (Ulf, Ast, Ogr; sh, th, kh one sound): met by a consonant they make a seam no
 *  tongue says (Astrdra, Ogrga), so the pair is drawn again, three times, then the end is one that opens on a vowel. */
const CLUSTER_END = /(?:[cgkpst]h|[bcdfgjklmnpqrstvwxz]){2}$/i;
const harsh = (x, y) => CLUSTER_END.test(x) && /^[^aeiouy]/i.test(y);
function twoPart(c, a, b) {
  let x = '',
    y = '';
  for (let tries = 0; tries < 3; tries++) {
    x = pick(c.r, a, c.fashion);
    y = pick(c.r, b, c.fashion ^ 0x51);
    if (!harsh(x, y)) break;
  }
  if (harsh(x, y)) {
    const soft = b.filter((v) => /^[aeiouy]/i.test(v));
    if (soft.length) y = soft[Math.floor(c.r() * soft.length)];
  }
  return cap(join(x, y));
}

