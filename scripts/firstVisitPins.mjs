// FIRST-VISIT (bible/07-Rendering/Performance-Priority.md FIRST-VISIT, "Refresh on update"): EACH KEPT ANSWER'S
// VERSION, GENERATED. src/firstVisitPins.js - gitignored, never committed - holds the pin of every kept answer's
// computation (tools/computationPin.mjs: the code that computes it and the shipped data it reads). A cache's key
// carries its pin, so a build whose computation changed is a new key and every player's kept answer is worked out
// again on their next launch; a build that did not change it keeps them. Nobody bumps a version by hand.
//
// Who writes it:
//   - `npm install` / `npm ci` (postinstall, this script): every checkout has the module before lint, the types or a
//     test reads it - and verify.yml runs this script in each job, whose dependencies a cache hit restores without
//     `npm ci`;
//   - every Vite build and dev server (firstVisitPinsPlugin, a vite.config.js plugin): the build writes it at its start
//     and the bundle takes the pins computed then, never what install left; the dev server answers with the pins as
//     they stand and computes them anew when a file a pin reads changes, so a dev edit is a new key as an update is.
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { isMain } from '../tools/lib/isMain.mjs';
import { firstVisitPins, firstVisitPinFiles } from '../tools/computationPin.mjs';

/** The generated module's whole text. */
export const pinsSource = (pins) => `// GENERATED by scripts/firstVisitPins.mjs (npm install, every Vite build and dev server) - do not edit, never
// commit: each FIRST-VISIT kept answer's computation pin (tools/computationPin.mjs).
export const FIRST_VISIT_PINS = Object.freeze(${JSON.stringify(pins)});
`;

export const PINS_PATH = 'src/firstVisitPins.js';

/** Write the pins module under `root`; answers the pins. */
export function writeFirstVisitPins(root) {
  const pins = firstVisitPins(root);
  writeFileSync(join(root, PINS_PATH), pinsSource(pins));
  return pins;
}

/** The Vite plugin: the pins computed by the build or the dev server itself (see the head of this file). */
export function firstVisitPinsPlugin() {
  let root = process.cwd(), building = false;
  /** @type {Set<string> | null} */
  let files = null;
  const norm = (p) => resolve(p).split('\\').join('/').toLowerCase();
  const isPins = (id) => norm(id.split('?')[0]) === norm(join(root, PINS_PATH));
  return {
    name: 'first-visit-pins',
    configResolved(config) { root = config.root; building = config.command === 'build'; },
    buildStart() { if (building) writeFirstVisitPins(root); },
    load(id) {
      if (!isPins(id)) return null;
      files = new Set([...firstVisitPinFiles(root)].map(norm));
      return pinsSource(firstVisitPins(root));
    },
    configureServer(server) {
      server.watcher.on('change', (file) => {
        if (!files?.has(norm(file))) return;
        for (const m of server.moduleGraph.getModulesByFile(join(root, PINS_PATH)) ?? []) server.moduleGraph.invalidateModule(m);
      });
    },
  };
}

if (isMain(import.meta.url)) {
  const pins = writeFirstVisitPins(fileURLToPath(new URL('..', import.meta.url)));
  console.log(`[first-visit] ${PINS_PATH}: ${Object.entries(pins).map(([k, v]) => `${k} ${v}`).join(', ')}`);
}
